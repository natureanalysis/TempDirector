#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_recognizes_tags() {
        assert_eq!(Locale::parse("zh-CN"), Some(Locale::Zh));
        assert_eq!(Locale::parse("zh"), Some(Locale::Zh));
        assert_eq!(Locale::parse("en-US"), Some(Locale::En));
        assert_eq!(Locale::parse("EN"), Some(Locale::En));
        assert_eq!(Locale::parse("fr"), None);
    }

    #[test]
    fn switch_changes_text() {
        set_locale(Locale::Zh);
        assert_eq!(t("err.busy"), "被占用：{e}");
        set_locale(Locale::En);
        assert_eq!(t("err.busy"), "In use: {e}");
        set_locale(Locale::Zh);
    }

    #[test]
    fn water_trigger_keys_present_in_both_locales() {
        set_locale(Locale::Zh);
        for key in [
            "water.auto_clean_log",
            "water.trigger.volume",
            "water.trigger.folder",
        ] {
            assert!(!t(key).is_empty(), "zh 缺键：{key}");
        }
        // 文件夹专属汇总键已并入统一键，不再单独存在。
        assert!(t("water.folder_auto_clean_log").is_empty());
        set_locale(Locale::En);
        for key in [
            "water.auto_clean_log",
            "water.trigger.volume",
            "water.trigger.folder",
        ] {
            assert!(!t(key).is_empty(), "en 缺键：{key}");
        }
        set_locale(Locale::Zh);
    }

    #[test]
    fn interpolates_placeholders() {
        set_locale(Locale::Zh);
        let s = tf(
            "io.failed",
            &[
                ("action", "搬运"),
                ("err", "boom"),
                ("hint", ""),
                ("path", "C:\\x"),
            ],
        );
        assert_eq!(s, "搬运失败：boom（路径：C:\\x）");
        set_locale(Locale::En);
        let s = tf(
            "io.failed",
            &[
                ("action", "move"),
                ("err", "boom"),
                ("hint", ""),
                ("path", "C:\\x"),
            ],
        );
        assert_eq!(s, "move failed: boom (path: C:\\x)");
        set_locale(Locale::Zh);
    }
}
